"""Deterministic extraction: tree-sitter for code, regex for SQL and Razor. No AI."""
import re
import sys
from dataclasses import dataclass, field

from .config import LangConfig
from .text import clean_comment, one_line

sys.setrecursionlimit(20000)

CLASS_LIKE = {"class", "interface", "struct", "record", "enum", "type"}
SCOPE_WRAPPERS = {"lexical_declaration", "variable_declaration", "export_statement", "decorated_definition"}


@dataclass
class Symbol:
    kind: str
    name: str
    qualified: str
    parent: int | None
    start_line: int
    end_line: int
    signature: str = ""
    doc: str = ""
    decorators: list[str] = field(default_factory=list)
    private: bool = False


@dataclass
class FileResult:
    lang: str
    lines: int
    symbols: list[Symbol] = field(default_factory=list)
    calls: list[tuple] = field(default_factory=list)      # (sym_idx|None, name, receiver, line)
    imports: list[str] = field(default_factory=list)
    routes: list[tuple] = field(default_factory=list)     # (sym_idx|None, method, path, handler)
    sql_refs: list[tuple] = field(default_factory=list)   # (sym_idx|None, table, op)
    meta: dict = field(default_factory=dict)
    idents: set = field(default_factory=set)              # type-like identifiers used in the file


# ---------------------------------------------------------------- shared regexes
_IDENT = re.compile(r"[A-Za-z_$][\w$]*")
SQL_HINT = re.compile(
    r"\bselect\b[\s\S]+?\bfrom\b|\binsert\s+into\b|\bupdate\s+[\[\]\w.]+\s+set\b|\bdelete\s+from\b"
    r"|\bmerge\s+into\b|\bexec(ute)?\s+[\[\]\w.]+", re.I)
SQL_TABLE = re.compile(
    r"\b(delete\s+from|insert\s+into|merge\s+into|from|join|into|update|exec|execute)\s+"
    r"([\[\]#\w]+(?:\.[\[\]#\w]+){0,2})", re.I)
SQL_NOT_TABLE = {"select", "where", "set", "values", "dual", "as", "on", "with", "(", "sp_executesql",
                 "the", "a", "an", "this", "that", "these", "those", "it", "my", "your", "our", "their",
                 "which", "each", "all", "any", "its", "his", "her", "one", "some", "table", "database"}

ROUTE_RES = [
    (re.compile(r"@[\w.]+\.(get|post|put|delete|patch|route|api_route|websocket)\(\s*[rfbu]?[\"']([^\"']*)", re.I), "verb_path"),
    (re.compile(r"\[\s*Http(Get|Post|Put|Delete|Patch|Head|Options)\s*(?:\(\s*@?\"([^\"]*)\")?"), "verb_path"),
    (re.compile(r"\[\s*Route\s*\(\s*@?\"([^\"]*)\""), "path"),
    (re.compile(r"@(Get|Post|Put|Delete|Patch)Mapping\s*(?:\(\s*(?:value\s*=\s*|path\s*=\s*)?\{?\s*\"([^\"]*)\")?"), "verb_path"),
    (re.compile(r"@RequestMapping\s*\(\s*(?:value\s*=\s*|path\s*=\s*)?\{?\s*\"([^\"]*)\""), "path"),
    (re.compile(r"@(Get|Post|Put|Delete|Patch|All)\s*\(\s*[\"'`]?([^\"'`)]*)"), "verb_path"),
    (re.compile(r"@Controller\s*\(\s*[\"'`]([^\"'`]*)"), "path"),
]
MINIMAL_API_RE = re.compile(
    r"\.Map(Get|Post|Put|Delete|Patch|Methods)\s*\(\s*@?\"([^\"]*)\"\s*(?:,\s*([A-Za-z_][\w.]*)\s*[,)])?")
MAP_GROUP_RE = re.compile(r"\.MapGroup\s*\(\s*@?\"([^\"]*)\"")
GENERATED_RE = re.compile(
    rb"<auto-generated|Generated by the protocol buffer compiler|DO NOT EDIT|@generated|This file was generated", re.I)
EXPRESS_RE = re.compile(r"\b(app|router|server|api)\.(get|post|put|delete|patch|all)\(\s*['\"`]([^'\"`]+)")


def callee_parts(text: str) -> tuple[str, str]:
    """'this.repo.Get<Order>(x)' -> ('Get', 'repo')"""
    t = text
    for _ in range(3):
        t = re.sub(r"<[^<>]*>", "", t)
        t = re.sub(r"\([^()]*\)", "", t)
    ids = _IDENT.findall(t)
    if not ids:
        return "", ""
    if len(ids) == 1 and re.search(r"(\.|->|::)\s*[A-Za-z_$][\w$]*\s*$", t):
        return ids[-1], "?"  # receiver is an expression ("a".join, f().x)
    return ids[-1], (ids[-2] if len(ids) > 1 else "")


def sql_tables(text: str) -> list[tuple[str, str]]:
    out = []
    for m in SQL_TABLE.finditer(text):
        kw, table = m.group(1).lower(), m.group(2)
        clean = table.replace("[", "").replace("]", "")
        if not clean or clean.lower() in SQL_NOT_TABLE or clean.startswith("@") or clean[0].isdigit():
            continue
        op = "exec" if kw.startswith("exec") else "read" if kw in ("from", "join") else "write"
        out.append((clean, op))
    return out


def parse_routes(decorators: list[str]) -> tuple[list[tuple[str, str]], list[str]]:
    """Return ([(VERB, path)], [path-only entries]) from decorator/attribute texts."""
    verbs, paths = [], []
    for d in decorators:
        for rx, mode in ROUTE_RES:
            for m in rx.finditer(d):
                if mode == "verb_path":
                    verb = m.group(1).upper()
                    verbs.append(("ANY" if verb in ("ROUTE", "API_ROUTE", "ALL") else verb, m.group(2)))
                else:
                    paths.append(m.group(1))
    return verbs, paths


# ---------------------------------------------------------------- tree-sitter
class TreeSitterExtractor:
    def __init__(self, cfg: LangConfig):
        from tree_sitter_language_pack import get_parser
        self.cfg = cfg
        self.parser = get_parser(cfg.grammar)

    def extract(self, rel: str, src: bytes) -> FileResult:
        self.src = src
        self.res = FileResult(lang=self.cfg.name, lines=src.count(b"\n") + 1)
        self.module = ""
        if self.cfg.module_from_path:
            stem = rel.rsplit(".", 1)[0].replace("/", ".")
            self.module = stem[:-9] if stem.endswith(".__init__") else stem
        self.groups, self.seen_routes = {}, set()
        tree = self.parser.parse(src)
        self._walk(tree.root_node, None)
        if self.cfg.name in ("javascript", "typescript", "tsx"):
            text = src.decode("utf-8", "replace")
            for m in EXPRESS_RE.finditer(text):
                self.res.routes.append((None, m.group(2).upper(), m.group(3), ""))
        self._resolve_routes()
        return self.res

    # -- helpers
    def _text(self, node) -> str:
        return self.src[node.start_byte:node.end_byte].decode("utf-8", "replace")

    def _name(self, node) -> str:
        n = node.child_by_field_name("name")
        if n is not None:
            return self._text(n).strip()
        for c in node.named_children:
            if c.type in ("variable_declaration",):
                for d in c.named_children:
                    if d.type == "variable_declarator":
                        nn = d.child_by_field_name("name")
                        return self._text(nn if nn is not None else d).split("=")[0].strip()
            if c.type in ("identifier", "scoped_identifier", "qualified_name", "type_identifier"):
                return self._text(c).strip()
        return ""

    def _decorators(self, node) -> list[str]:
        cfg, out = self.cfg, []
        if not cfg.decorators:
            return out
        for c in node.children:
            if c.type in cfg.decorators:
                out.append(one_line(self._text(c), 200))
            elif c.type in cfg.decorator_containers:
                out += [one_line(self._text(x), 200) for x in c.children if x.type in cfg.decorators]
        p = node.parent
        if p is not None and p.type in cfg.decorator_wrappers:
            out += [one_line(self._text(c), 200) for c in p.children if c.type in cfg.decorators]
        prev = node.prev_named_sibling
        while prev is not None and prev.type in cfg.decorators:
            out.insert(0, one_line(self._text(prev), 200))
            prev = prev.prev_named_sibling
        return list(dict.fromkeys(out))

    def _signature(self, node, value=None) -> str:
        start = node.start_byte
        for c in node.children:
            if c.type in self.cfg.decorators or c.type in self.cfg.decorator_containers and \
                    all(x.type in self.cfg.decorators for x in c.named_children):
                start = max(start, c.end_byte)
        body = (value or node).child_by_field_name("body")
        if body is not None and body.start_byte > start:
            end = body.start_byte
        else:
            end = self.src.find(b"\n", start)
            end = node.end_byte if end == -1 or end > node.end_byte else end
        sig = self.src[start:end].decode("utf-8", "replace")
        if self.cfg.name == "python":
            sig = re.sub(r"\s+#[^\n]*", " ", sig)
        sig = re.sub(r"(\s*=>\s*|\s*[:{;=]\s*)+$", "", sig.strip())
        return one_line(sig, 220)

    def _doc(self, node) -> str:
        if self.cfg.doc_style == "python":
            body = node.child_by_field_name("body")
            if body is not None and body.named_child_count:
                first = body.named_children[0]
                if first.type == "expression_statement" and first.named_child_count:
                    first = first.named_children[0]
                if first.type == "string":
                    raw = self._text(first).lstrip("rRbBuUfF").strip("\"'")
                    return one_line(raw, 400)
        anchor = node
        while anchor.parent is not None and anchor.parent.type in SCOPE_WRAPPERS:
            anchor = anchor.parent
        parts, row = [], anchor.start_point[0]
        prev = anchor.prev_sibling
        while prev is not None and (prev.type in self.cfg.decorators):
            row = prev.start_point[0]
            prev = prev.prev_sibling
        while prev is not None and "comment" in prev.type and prev.end_point[0] >= row - 1:
            parts.insert(0, self._text(prev))
            row = prev.start_point[0]
            prev = prev.prev_sibling
        return one_line(clean_comment("\n".join(parts)), 400) if parts else ""

    # -- walk
    def _walk(self, node, scope):
        cfg, res = self.cfg, self.res
        t = node.type
        kind = cfg.kinds.get(t)
        value = None
        if kind is None and cfg.var_function_node and t == cfg.var_function_node:
            value = node.child_by_field_name("value")
            if value is not None and value.type in cfg.var_function_values:
                kind = "function"
            else:
                value = None
        new_scope = scope
        if kind:
            name = self._name(node)
            if name:
                parent = res.symbols[scope] if scope is not None else None
                if kind == "function" and parent is not None and parent.kind in CLASS_LIKE:
                    kind = "method"
                recv = node.child_by_field_name(cfg.receiver_field) if cfg.receiver_field else None
                owner = ""
                if recv is not None and parent is None:  # Go `func (c *Command) Run()` -> module.Command.Run
                    owner = re.findall(r"\w+", re.sub(r"\[[^\]]*\]", "", self._text(recv)))[-1] + "."
                if parent is not None:
                    qualified = f"{parent.qualified}.{name}"
                else:
                    qualified = f"{self.module}.{owner}{name}" if self.module else owner + name
                decorators = self._decorators(node)
                sig = self._signature(node, value)
                base = name.split(".")[-1]
                private = (base.startswith("_") and not (base.startswith("__") and base.endswith("__"))) \
                    or base.startswith("#") or bool(re.search(r"\bprivate\b", sig))
                res.symbols.append(Symbol(
                    kind=kind, name=name, qualified=qualified, parent=scope,
                    start_line=node.start_point[0] + 1, end_line=node.end_point[0] + 1,
                    signature=sig, doc=self._doc(node), decorators=decorators, private=private))
                new_scope = len(res.symbols) - 1
        if t in cfg.calls:
            fld = cfg.calls[t]
            target = node.child_by_field_name(fld)
            if target is not None:
                name, receiver = callee_parts(self._text(target))
                if fld == "name":
                    obj = node.child_by_field_name("object")
                    receiver = callee_parts(self._text(obj))[0] if obj is not None else ""
                if name:
                    res.calls.append((new_scope, name, receiver, node.start_point[0] + 1))
        if t in cfg.calls and self.cfg.name == "csharp":
            head = self._text(node)[:400]
            g = MAP_GROUP_RE.search(head)
            if g:
                self.groups[new_scope] = g.group(1).strip("/")
            m = MINIMAL_API_RE.search(head)
            key = (new_scope, m.group(1), m.group(2)) if m else None
            if m and key not in self.seen_routes:
                self.seen_routes.add(key)
                verb = "ANY" if m.group(1) == "Methods" else m.group(1).upper()
                handler = m.group(3) or ""
                prefix = self.groups.get(new_scope, "")
                path = "/".join(x for x in (prefix, m.group(2).strip("/")) if x)
                res.routes.append((new_scope, verb, "/" + path, handler.split(".")[-1]))
                if handler:
                    name, receiver = callee_parts(handler)
                    res.calls.append((new_scope, name, receiver, node.start_point[0] + 1))
        if t in cfg.imports:
            res.imports.append(one_line(self._text(node), 200))
        if t in cfg.strings:
            text = self._text(node)
            if SQL_HINT.search(text):
                for table, op in sql_tables(text):
                    if op == "exec":
                        parts = table.split(".")
                        res.calls.append((new_scope, parts[-1], parts[-2] if len(parts) > 1 else "", node.start_point[0] + 1))
                    else:
                        res.sql_refs.append((new_scope, table, op))
        if node.child_count == 0 and "identifier" in t:
            word = self.src[node.start_byte:node.end_byte]
            if len(word) >= 3 and word[:1].isupper():
                res.idents.add(word.decode("utf-8", "replace"))
        cur = new_scope
        for child in node.children:
            ns = self._walk(child, cur)
            if ns is not None:
                cur = ns  # file-scoped namespace: following siblings live inside it
        if kind == "namespace" and t.startswith("file_scoped") and new_scope != scope:
            res.symbols[new_scope].end_line = (node.parent.end_point[0] + 1) if node.parent else res.symbols[new_scope].end_line
            return new_scope
        return None

    def _resolve_routes(self):
        syms = self.res.symbols
        prefix: dict[int, str] = {}
        for i, s in enumerate(syms):
            verbs, paths = parse_routes(s.decorators)
            if s.kind in CLASS_LIKE:
                if paths or verbs:
                    p = (paths or [v[1] or "" for v in verbs])[0]
                    prefix[i] = p.replace("[controller]", re.sub(r"Controller$", "", s.name))
                continue
            if not verbs and paths:
                verbs = [("ANY", paths[0])]
            if not verbs:
                continue
            base, anc = "", s.parent
            while anc is not None:
                if anc in prefix:
                    base = prefix[anc]
                    break
                anc = syms[anc].parent
            for verb, path in verbs:
                path = path if path is not None else (paths[0] if paths else "")
                path = (path or "").replace("[action]", s.name)
                full = path if path.startswith("/") or not base else f"{base.rstrip('/')}/{path.lstrip('/')}"
                if not full and self.cfg.name == "csharp":
                    owner = syms[s.parent].name if s.parent is not None else ""
                    if owner.endswith("Controller"):
                        full = f"{owner[:-10]}/{s.name}"  # conventional MVC route
                self.res.routes.append((i, verb, "/" + full.strip("/") if full else "/" + base.strip("/"), ""))


# ---------------------------------------------------------------- regex extractors
SQL_CREATE = re.compile(
    r"^[ \t]*(?:create\s+or\s+alter|create|alter)\s+(procedure|proc|function|view|table|trigger|type)\s+"
    r"([\[\]#\w]+(?:\.[\[\]#\w]+){0,2})", re.I | re.M)
SQL_KIND = {"procedure": "procedure", "proc": "procedure", "function": "function", "view": "view",
            "table": "table", "trigger": "trigger", "type": "type"}


def extract_sql(rel: str, src: bytes) -> FileResult:
    text = src.decode("utf-8", "replace")
    lines = text.splitlines()
    res = FileResult(lang="sql", lines=len(lines) + 1)
    matches = list(SQL_CREATE.finditer(text))
    for i, m in enumerate(matches):
        start = text.count("\n", 0, m.start()) + 1
        end = (text.count("\n", 0, matches[i + 1].start())) if i + 1 < len(matches) else len(lines)
        qualified = m.group(2).replace("[", "").replace("]", "")
        doc, j = [], start - 2
        while j >= 0 and (lines[j].strip().startswith("--") or lines[j].strip().startswith(("/*", "*"))):
            doc.insert(0, lines[j])
            j -= 1
        res.symbols.append(Symbol(
            kind=SQL_KIND[m.group(1).lower()], name=qualified.split(".")[-1], qualified=qualified,
            parent=None, start_line=start, end_line=max(start, end),
            signature=one_line(lines[start - 1], 220), doc=one_line(clean_comment("\n".join(doc)), 400)))
        body = "\n".join(lines[start:end])
        idx = len(res.symbols) - 1
        for table, op in sql_tables(body):
            if op == "exec":
                res.calls.append((idx, table.split(".")[-1], table.split(".")[0] if "." in table else "", start))
            else:
                res.sql_refs.append((idx, table, op))
    if not matches:
        for table, op in sql_tables(text):
            res.sql_refs.append((None, table, op))
    return res


RAZOR_PAGE = re.compile(r'^@page\s+"([^"]+)"', re.M)
RAZOR_TYPE = re.compile(r"^@(model|inherits|inject)\s+([\w.<>]+)", re.M)


def extract_razor(rel: str, src: bytes) -> FileResult:
    text = src.decode("utf-8", "replace")
    res = FileResult(lang="razor", lines=text.count("\n") + 1)
    for m in RAZOR_PAGE.finditer(text):
        res.routes.append((None, "PAGE", m.group(1), ""))
    for m in RAZOR_TYPE.finditer(text):
        name, _ = callee_parts(m.group(2))
        res.meta.setdefault(m.group(1), []).append(m.group(2))
        if name:
            res.calls.append((None, name, "", text.count("\n", 0, m.start()) + 1))
    return res


REGEX_EXTRACTORS = {"sql_regex": extract_sql, "razor_regex": extract_razor}
